defmodule ElixirKatasWeb.ExportController do
  use ElixirKatasWeb, :controller
  require Logger
  alias ElixirKatas.CSV.MyParser

  def csv(conn, _params) do
    # Sample data
    headers = ["ID", "Name", "Role", "Joined Date"]
    data = [
      [1, "Alice Smith", "Engineer", "2024-01-15"],
      [2, "Bob Jones", "Designer", "2024-02-01"],
      [3, "Charlie Brown", "Manager", "2024-03-10"],
      [4, "Dana White", "Director", "2023-11-20"],
      [5, "Evan Green", "Developer", "2024-01-05"]
    ]

    csv_content = 
      [headers | data]
      |> MyParser.dump_to_iodata()

    conn
    |> put_resp_content_type("text/csv")
    |> put_resp_header("content-disposition", "attachment; filename=\"users_export.csv\"")
    |> send_resp(200, csv_content)
  end
  def pdf(conn, %{"title" => title, "body" => body}) when is_binary(title) and is_binary(body) do
    # Both fields come from the visitor and the HTML is rendered by headless
    # Chrome on the server, so never let raw HTML through.
    title = title |> Phoenix.HTML.html_escape() |> Phoenix.HTML.safe_to_string()
    body = ElixirKatasWeb.Markdown.safe_html(body)

    html = """
    <!DOCTYPE html>
    <html>
      <head>
        <meta charset="utf-8">
        <style>
          @page { size: A4; }
          body { font-family: sans-serif; padding: 2em; }
          h1 { color: #4338ca; border-bottom: 2px solid #e5e7eb; padding-bottom: 0.5em; }
          .content { margin-top: 2em; line-height: 1.6; color: #374151; }
          .footer { margin-top: 4em; font-size: 0.8em; color: #9ca3af; border-top: 1px solid #e5e7eb; padding-top: 1em; }
        </style>
      </head>
      <body>
        <h1>#{title}</h1>
        <div class="content">
          #{body}
        </div>
        <div class="footer">
          Generated by Phoenix LiveView Katas | #{Date.utc_today()}
        </div>
      </body>
    </html>
    """

    case ElixirKatas.Pdf.from_html(html) do
      {:ok, pdf_content} ->
        conn
        |> put_resp_content_type("application/pdf")
        |> put_resp_header("content-disposition", "attachment; filename=\"document.pdf\"")
        |> send_resp(200, pdf_content)

      {:error, reason} ->
        Logger.error("PDF export failed: #{inspect(reason)}")

        message =
          if reason == :chrome_not_found,
            do: "PDF export needs Google Chrome or Chromium installed on the server.",
            else: "Could not generate the PDF. Please try again."

        conn
        |> put_flash(:error, message)
        |> redirect(to: ~p"/liveview-katas/98-pdf")
    end
  end
end
